#pragma once

namespace miit::algebra
{
    /**
     * @brief Абстрактный базовый класс генератора целочисленных значений
     *
     * Наследники определяют конкретный алгоритм получения числа:
     * случайное число, число из потока ввода или постоянное число.
     * Класс не содержит данных и задаёт только единый интерфейс generate().
     */
    class Generator
    {
    public:
        /**
         * @brief Виртуальный деструктор
         *
         * Нужен для корректного удаления объекта через указатель на base.
         * Благодаря ему вызов delete Generator* вызовет деструктор наследника.
         */
        virtual ~Generator() = default;

        /**
         * @brief Получить очередное целое число
         * @return Сгенерированное значение, которое будет записано в матрицу
         */
        virtual int generate() = 0;
    };
}
